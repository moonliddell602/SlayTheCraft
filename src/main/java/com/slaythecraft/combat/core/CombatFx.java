package com.slaythecraft.combat.core;

/**
 * 战斗**表现层事件**（v0.3.0）。
 *
 * <p>引擎是纯逻辑的：它不认识实体、音效和动画。但它知道"谁打了谁、谁被挡住了"，
 * 所以它在发生事情时广播这些语义事件；Minecraft 层把事件翻译成"往前冲一下 / 蹲一下 /
 * 被击退 + 音效"。这样动画规则和战斗规则始终使用同一份判定（例如"完全被格挡"与
 * "真的掉血"是引擎算出来的，不会出现界面和日志不一致）。</p>
 */
public enum CombatFx {

    /** 玩家打出一张攻击牌（向前冲一下 + 暴击音效）。 */
    PLAYER_ATTACK,
    /** 玩家打出一张给自己上格挡的牌（蹲起一次 + 穿甲音效）。 */
    PLAYER_BLOCK,
    /** 玩家真的掉血了（受击动画 + 受伤音效）。 */
    PLAYER_HURT,
    /** 玩家的伤害被格挡完全吸收（盾牌格挡音效，不位移）。 */
    PLAYER_HURT_BLOCKED,
    /** 敌人发动攻击（敌人向前冲一下 + 暴击音效）。 */
    ENEMY_ATTACK,
    /** 敌人被打中（轻微后仰）。 */
    ENEMY_HURT,
    /** 敌人获得格挡（v0.4.1：和玩家一样蹲一下 + 穿甲音效）。 */
    ENEMY_BLOCK,
    /** 充能球造成伤害（v0.4.1：需求"充能球结算造成伤害时没有音效"）。 */
    ORB_DAMAGE,
    /** 充能球给格挡（冰球的被动 / 激发）。 */
    ORB_BLOCK,
    /**
     * 敌人发动**非攻击类特殊效果**（v0.5.0.5）。
     *
     * <p>需求原文："敌人执行特殊效果时（如 施加虚弱）没有动画，需要补全。例如播放唤魔者施法的音效，
     * 并在敌人实体放出药水粒子特效（作为显示敌人对玩家施加效果的动画）。"</p>
     *
     * <p>覆盖：上虚弱 / 易伤 / 灼烧 / 凋零 / 中毒 / 缓慢等负面效果，以及给自己上力量这类增益。</p>
     */
    ENEMY_CAST,
    /**
     * 敌人**自爆**（v0.5.0.8：旋风人蓄能结算）。
     *
     * <p>需求原文："在结算时播放爆炸动画。"</p>
     */
    ENEMY_EXPLODE,
    /**
     * 玩家在**有集中**的状态下生成了一颗**冰球**（v0.5.0.10 成就【集中冰才对】）。
     *
     * <p>需求："在拥有集中状态时，生成冰球。" 引擎只负责广播"这件事发生了"，
     * 具体给谁记成就由 MC 层（{@code CombatFxBus}）决定。</p>
     */
    FROST_CHANNELLED,
    /**
     * 某名玩家**连续打出了 4 张同名手牌**（v0.5.0.10 隐藏成就【回响形态了 回响形态】）。
     *
     * <p>需求："连续打出 4 张同名手牌。"</p>
     */
    FOUR_SAME_CARDS
}
